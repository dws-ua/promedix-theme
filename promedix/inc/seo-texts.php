/** HTML of the collapsible SEO block for a key, or ''. */
function promedix_seo_block( $key ) {
	$t = promedix_seo_texts();
	if ( empty( $t[ $key ] ) ) {
		return '';
	}
	return '<section class="pmx-container pmx-seo-wrap"><details class="wp-block-details pmx-seo"><summary>' . esc_html( $t[ $key ]['title'] ) . '</summary><div class="pmx-prose">' . wp_kses_post( $t[ $key ]['html'] ) . '</div></details></section>';
}

/* [promedix_seo key="…"]: key "auto" picks the current page slug or term slug. */
add_shortcode( 'promedix_seo', function ( $atts ) {
	$atts = shortcode_atts( array( 'key' => 'auto' ), $atts, 'promedix_seo' );
	$key  = $atts['key'];
	if ( 'auto' === $key ) {
		$o   = get_queried_object();
		$key = $o instanceof WP_Term ? $o->slug : ( $o instanceof WP_Post ? $o->post_name : '' );
		if ( function_exists( 'is_shop' ) && is_shop() ) {
			$key = 'shop';
		}
		if ( 'dlia-komand' !== $key && $o instanceof WP_Post && 'page-b2b' === get_page_template_slug( $o ) ) {
			$key = 'dlia-komand';
		}
	}
	return promedix_seo_block( $key );
} );
