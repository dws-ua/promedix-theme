/** Current landing settings or null. */
function promedix_current_landing() {
	$slug = get_post_field( 'post_name', get_queried_object_id() );
	$all  = promedix_landings();
	return isset( $all[ $slug ] ) ? $all[ $slug ] + array( 'slug' => $slug ) : null;
}

/* Products, catalog link and links to the other profession pages: [promedix_landing] */
add_shortcode( 'promedix_landing', function () {
	$l = promedix_current_landing();
	if ( ! $l || ! function_exists( 'wc_get_page_permalink' ) ) {
		return '';
	}
	if ( ! empty( $l['match'] ) ) {
		$ids = array();
		foreach ( wc_get_products( array( 'limit' => 50, 'status' => 'publish', 'return' => 'ids' ) ) as $id ) {
			if ( false !== strpos( get_post_field( 'post_name', $id ), $l['match'] ) ) {
				$ids[] = $id;
			}
		}
		$sc = '[products limit="8" columns="4" ids="' . esc_attr( implode( ',', $ids ) ) . '" orderby="popularity" visibility="visible"]';
	} elseif ( $l['cat'] ) {
		$sc = '[products limit="8" columns="4" category="' . esc_attr( $l['cat'] ) . '" orderby="popularity" visibility="visible"]';
	} else {
		$sc = '[products limit="8" columns="4" orderby="popularity" visibility="visible"]';
	}
	$h  = '<div class="pmx-container pmx-landing">';
	$h .= '<section class="pmx-block" id="pmx-pick"><h2>' . esc_html__( 'Оберіть свою пару', 'promedix' ) . '</h2>' . do_shortcode( $sc )
		. '<p class="pmx-more pmx-pick__all"><a class="pmx-btn pmx-btn--secondary" href="' . esc_url( wc_get_page_permalink( 'shop' ) ) . '">' . esc_html__( 'Переглянути весь каталог', 'promedix' ) . '</a></p></section>';
	$h .= '</div>';
	return $h;
} );

/* Links to all profession pages (landings + the three main ones): [promedix_landing_links] */
add_shortcode( 'promedix_landing_links', function () {
	$cur   = get_post_field( 'post_name', get_queried_object_id() );
	$items = array();
	foreach ( array( 'medics', 'hair', 'beauty' ) as $k ) {
		$url = promedix_link( $k );
		if ( $url ) {
			$p             = get_page_by_path( promedix_page_slugs()[ $k ] );
			$items[ $url ] = $p ? get_the_title( $p ) : $k;
		}
	}
	foreach ( promedix_landings() as $slug => $l ) {
		$p = get_page_by_path( $slug );
		if ( $p && 'publish' === $p->post_status && $slug !== $cur ) {
			$items[ get_permalink( $p ) ] = $l['h1'];
		}
	}
	if ( ! $items ) {
		return '';
	}
	$h = '<section class="pmx-container pmx-block pmx-landing-links" aria-labelledby="pmx-ll-t"><h2 id="pmx-ll-t" class="pmx-h3">' . esc_html__( 'Взуття за професією', 'promedix' ) . '</h2><ul>';
	foreach ( $items as $url => $t ) {
		$h .= '<li><a href="' . esc_url( $url ) . '">' . esc_html( $t ) . '</a></li>';
	}
	return $h . '</ul></section>';
} );
